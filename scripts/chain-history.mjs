#!/usr/bin/env node
/**
 * Generates app/research/data/chainHistory.ts: Ethereum Classic's monthly block time, difficulty and
 * hashrate since genesis, read from Blockscout. /research/history charts it and computes any month after
 * the file's last one live (lib/chain-history.ts), so regenerating only keeps that top-up short.
 *
 *   node scripts/chain-history.mjs
 *
 * A month runs from the first block at or after its first second to the first block of the next month.
 * Blockscout's monthly block counts give the first guess at each boundary; they miss about 133 hours of
 * blocks in September 2023, so every guess is checked against the block's own timestamp and moved until
 * it lies within ten minutes of the month's start. A month's average block time comes from its boundary
 * blocks' timestamps; difficulty is read at its middle block, and hashrate is that difficulty divided by
 * the average block time, the formula lib/hashrate.ts applies to the current figure. Requests go one at
 * a time with a pause, as Blockscout limits bursts; a full run takes several minutes.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const BLOCKSCOUT = 'https://etc.blockscout.com'
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'research', 'data', 'chainHistory.ts')
const PAUSE_MS = 1200
const TOLERANCE_S = 600

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function getJson(url, attempt = 1) {
  await sleep(PAUSE_MS)
  const response = await fetch(url, { headers: { Accept: 'application/json', 'User-Agent': 'ethereumclassic.com chain-history script' } })
  if (response.status === 429 && attempt < 8) {
    await sleep(attempt * 15000)
    return getJson(url, attempt + 1)
  }
  if (!response.ok) throw new Error(`${url}: ${response.status}`)
  return response.json()
}

async function block(height) {
  const body = await getJson(`${BLOCKSCOUT}/api/v2/blocks/${height}`)
  return { height, seconds: Date.parse(body.timestamp) / 1000, difficulty: Number(body.difficulty) }
}

/** A block within TOLERANCE_S of `target` seconds, starting from `guess` and stepping by the local block time. */
async function blockNear(target, guess) {
  let b = await block(guess)
  for (let i = 0; i < 12 && Math.abs(target - b.seconds) > TOLERANCE_S; i++) {
    const probe = await block(Math.max(1, b.height - 1000))
    const blockTime = (b.seconds - probe.seconds) / (b.height - probe.height) || 13
    b = await block(Math.max(1, b.height + Math.round((target - b.seconds) / blockTime)))
  }
  if (Math.abs(target - b.seconds) > TOLERANCE_S) throw new Error(`no block near ${new Date(target * 1000).toISOString()}`)
  return b
}

async function main() {
  const counts = await getJson(`${BLOCKSCOUT}/stats-service/api/v1/lines/newBlocks?resolution=MONTH`)
  const countByMonth = new Map(counts.chart.map((point) => [point.date.slice(0, 7), Number(point.value)]))
  const now = new Date()
  const limit = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1)
  // Boundaries: August 1, 2015 (the first full month) up to the first of the current month.
  const starts = []
  for (let d = new Date(Date.UTC(2015, 7, 1)); d.getTime() <= limit; d.setUTCMonth(d.getUTCMonth() + 1)) starts.push(new Date(d))
  const boundaries = []
  let guess = 13775 // the first block of August 2015
  for (const start of starts) {
    const b = await blockNear(start.getTime() / 1000, guess)
    boundaries.push(b)
    guess = b.height + (countByMonth.get(start.toISOString().slice(0, 7)) ?? 190000)
    process.stdout.write(`${start.toISOString().slice(0, 7)} starts near block ${b.height}\n`)
  }
  const rows = []
  for (let i = 0; i < boundaries.length - 1; i++) {
    const first = boundaries[i]
    const next = boundaries[i + 1]
    const blocks = next.height - first.height
    const mid = await block(first.height + Math.floor(blocks / 2))
    const blockTime = (next.seconds - first.seconds) / blocks
    rows.push({
      month: starts[i].toISOString().slice(0, 7),
      firstBlock: first.height,
      blocks,
      blockTimeSeconds: Math.round(blockTime * 100) / 100,
      difficultyPH: Math.round((mid.difficulty / 1e15) * 1e6) / 1e6,
      hashrateTHs: Math.round((mid.difficulty / blockTime / 1e12) * 1000) / 1000,
    })
    const r = rows[rows.length - 1]
    process.stdout.write(`${r.month} ${r.blocks} blocks, ${r.blockTimeSeconds}s, ${r.hashrateTHs} TH/s\n`)
  }
  const generated = now.toISOString().slice(0, 10)
  const body = `/**
 * Generated by scripts/chain-history.mjs on ${generated} from Blockscout. Do not edit by hand: run
 * \`node scripts/chain-history.mjs\` to regenerate. One row per complete month since August 2015: its first block
 * (within ten minutes of the month's start), its block count, its average block time in seconds, the
 * difficulty at its middle block in petahash (1e15), and hashrate in TH/s, that difficulty divided by the
 * average block time.
 */
export interface ChainMonth {
  month: string
  firstBlock: number
  blocks: number
  blockTimeSeconds: number
  difficultyPH: number
  hashrateTHs: number
}

export const CHAIN_HISTORY_GENERATED = '${generated}'

export const CHAIN_HISTORY: ChainMonth[] = [
${rows.map((r) => `  { month: '${r.month}', firstBlock: ${r.firstBlock}, blocks: ${r.blocks}, blockTimeSeconds: ${r.blockTimeSeconds}, difficultyPH: ${r.difficultyPH}, hashrateTHs: ${r.hashrateTHs} },`).join('\n')}
]
`
  writeFileSync(OUT, body)
  process.stdout.write(`wrote ${rows.length} months to ${path.relative(process.cwd(), OUT)}\n`)
}

main().catch((error) => {
  process.stderr.write(`${error.stack ?? error}\n`)
  process.exit(1)
})
